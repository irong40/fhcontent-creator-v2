/**
 * Every writer of a quote_video script stores the helper's script, so the speaker is named once
 * (qcheck r1 F4, 2026-11-24). The model below returns the doubled line the fault produced; each
 * route must store the built script instead.
 */
import { describe, it, expect, vi, beforeEach } from 'vitest';
import { NextRequest } from 'next/server';

const PASSAGE = 'Everybody can be great because everybody can serve. You do not have to have a college degree to serve. You only need a heart full of grace, a soul generated by love.';
const SOURCE = 'Martin Luther King, The Drum Major Instinct, sermon';
const BUILT = `${PASSAGE}\n\n— ${SOURCE}`;
const DOUBLED = `${PASSAGE}\n\n— Martin Luther King, ${SOURCE}`;

const state = vi.hoisted(() => ({
    topic: {} as Record<string, unknown>,
    piece: {} as Record<string, unknown>,
    inserts: [] as { table: string; row: Record<string, unknown> }[],
    updates: [] as { table: string; row: Record<string, unknown> }[],
    modelText: '',
}));

vi.mock('@/lib/supabase/server', () => ({
    createAdminClient: () => ({
        from: (table: string) => ({
            select: () => ({
                eq: () => ({
                    single: async () => ({ data: table === 'topics' ? state.topic : state.piece, error: null }),
                }),
            }),
            update: (row: Record<string, unknown>) => {
                state.updates.push({ table, row });
                return { eq: async () => ({ error: null }) };
            },
            insert: (row: Record<string, unknown>) => {
                state.inserts.push({ table, row });
                const done = { error: null };
                return Object.assign(Promise.resolve(done), {
                    select: () => ({ single: async () => ({ data: { id: 'piece-new' }, error: null }) }),
                });
            },
            delete: () => {
                const chain = { eq: () => Object.assign(Promise.resolve({ error: null }), chain) };
                return chain;
            },
        }),
    }),
}));
vi.mock('@/lib/claude', () => ({
    claude: { generateContent: vi.fn(async () => ({ text: state.modelText, inputTokens: 1, outputTokens: 1 })) },
}));
vi.mock('@/lib/prompts', () => ({
    buildContentPrompt: () => ({ system: 's', user: 'u' }),
    buildRemixPrompt: () => ({ system: 's', user: 'u', maxTokens: 100 }),
}));

import { POST as generate } from './generate/route';
import { POST as regenerate } from './[id]/regenerate/route';
import { POST as remix } from './[id]/remix/route';

const req = (body: unknown) => new NextRequest('https://fixture/api/content', { method: 'POST', body: JSON.stringify(body) });
const params = { params: Promise.resolve({ id: 'piece-1' }) };
const storedScript = (rows: { table: string; row: Record<string, unknown> }[]) =>
    rows.filter(r => r.table === 'content_pieces' && 'script' in r.row).at(-1)?.row.script;

describe('quote_video script writers name the speaker once', () => {
    beforeEach(() => {
        vi.clearAllMocks();
        state.inserts = [];
        state.updates = [];
        state.topic = {
            id: 'topic-1',
            title: 'Martin Luther King: The Drum Major Instinct',
            hook: 'h',
            personas: { name: 'Fixture', content_format: 'quote_video' },
            historical_points: [{ claim: PASSAGE, quote: PASSAGE, source: SOURCE, year: '' }],
        };
        state.piece = { id: 'piece-1', topic_id: 'topic-1', piece_type: 'quote_video', script: DOUBLED };
    });

    it('generate stores the built script, not the model script', async () => {
        state.modelText = JSON.stringify({ pieces: [{ pieceType: 'quote_video', script: DOUBLED, captionLong: 'c', captionShort: 'c' }] });
        const res = await generate(req({ topicId: '11111111-1111-4111-8111-111111111111' }));
        expect(res.status).toBe(200);
        expect(storedScript(state.inserts)).toBe(BUILT);
    });

    it('regenerate stores the built script, not the model script', async () => {
        state.modelText = JSON.stringify({ pieceType: 'long', script: DOUBLED, captionLong: 'c', captionShort: 'c' });
        const res = await regenerate(req({}), params);
        expect(res.status).toBe(200);
        expect(storedScript(state.updates)).toBe(BUILT);
    });

    it('remix of the script stores the built script, not the model script', async () => {
        state.modelText = JSON.stringify({ script: DOUBLED });
        const res = await remix(req({ field: 'script' }), params);
        expect(res.status).toBe(200);
        expect(storedScript(state.updates)).toBe(BUILT);
    });

    it('regenerate keeps the model script for a piece that is not a quote video', async () => {
        state.piece = { ...state.piece, piece_type: 'long' };
        state.topic = { ...state.topic, personas: { name: 'Fixture', content_format: 'standard' } };
        state.modelText = JSON.stringify({ pieceType: 'long', script: 'model long script', captionLong: 'c', captionShort: 'c' });
        const res = await regenerate(req({}), params);
        expect(res.status).toBe(200);
        expect(storedScript(state.updates)).toBe('model long script');
    });
});
